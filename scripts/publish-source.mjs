#!/usr/bin/env node
// Copies the committed tree into the public source repo as one new commit.
// This repo stays private: its history carries the owner's personal address and
// old Sadaa-era screenshots and internal docs, so the public repo gets snapshots, not history.
//
//   node scripts/publish-source.mjs --clone <path to a clone of the public repo> --version X.Y.Z [--push]
//
// It builds the snapshot in a temporary worktree of the clone and commits it to a
// new `source-vX.Y.Z` branch cut from the public main; the clone is untouched if a
// step fails. Without --push it stops there, so the result can be read first; with
// it, the branch is pushed and a PR opened, to merge like any other change.
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdtempSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC_REPO = "wasimjalali/usefulvoice";
const AUTHOR = "Wasim Jalali <245747147+wasimjalali@users.noreply.github.com>";
// Never public: old Sadaa-era audits, plans and screenshots (they show the owner's
// real windows and data) and any media that could. Each line says why.
const EXCLUDE = [
  // Sadaa-era UI audits, walkthrough and screenshots of the owner's real windows.
  /^docs\/release\//,
  // Screenshots of real data: notes.png shows an internal note, dictionary.png real vocabulary with counts.
  // Captures with synthetic data go here once the owner approves them.
  /^docs\/images\//,
  // Sadaa-era internal specs and plans, with the owner's working paths and old product names.
  /^docs\/superpowers\//,
  // The June 2026 Sadaa bug audit: internal, written against the old app name.
  /^docs\/BUGS_2026-06-11\.md$/,
  // Screenshots and recordings under the audit reports could show real dictations.
  /^docs\/audit\/.*\.(png|jpe?g|webp|gif|mp4|mov|html)$/i,
  // Eval frames and recordings could show real windows; the cases, scripts and results stay.
  /^evals\/.*\.(png|jpe?g|webp|gif|mp4|mov)$/i,
  // Browser-automation captures dropped in the repo root (also gitignored; belt and braces).
  /^[^/]+\.(png|jpe?g|ya?ml)$/i,
  // The Playwright MCP scratch folder: page snapshots and screenshots of real sessions.
  /^\.playwright-mcp\//,
  // Windows E2E output: screenshots, videos and traces of fixture runs, regenerated by CI.
  /^windows\/e2e-results\//,
];

const { values } = parseArgs({
  options: {
    clone: { type: "string" },
    version: { type: "string" },
    push: { type: "boolean", default: false },
    "push-existing": { type: "boolean", default: false },
  },
});
if (!values.clone || !values.version || !/^\d+\.\d+\.\d+$/.test(values.version)) {
  process.stderr.write("usage: publish-source.mjs --clone <path> --version X.Y.Z [--push | --push-existing]\n");
  process.exit(2);
}
if (values.push && values["push-existing"]) {
  process.stderr.write("use --push or --push-existing, not both\n");
  process.exit(2);
}
const git = (cwd, ...args) => execFileSync("git", args, { cwd, encoding: "utf8" }).trim();
// Untrimmed: for NUL-delimited output, where trimming would eat a leading space in a file name.
const gitRaw = (cwd, ...args) => execFileSync("git", args, { cwd, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
// Every effective URL of the clone's origin (fetch and push) must be the public repo.
const REMOTE_RE = new RegExp(`^(https://github\\.com/|git@github\\.com:)${PUBLIC_REPO}(\\.git)?$`);
if (git(ROOT, "status", "--porcelain", "--untracked-files=no") !== "") throw new Error("commit first: the tree has uncommitted changes");
const clone = path.resolve(values.clone);
if (!existsSync(path.join(clone, ".git"))) throw new Error(`${clone} is not a git clone`);
// `remote get-url` applies url.<base>.insteadOf and pushInsteadOf, and `--push` applies
// remote.origin.pushurl, so these are the URLs git would really talk to. Checked before any fetch.
for (const flags of [[], ["--push"]]) {
  const urls = git(clone, "remote", "get-url", ...flags, "--all", "origin").split("\n").filter(Boolean);
  const bad = urls.filter((u) => !REMOTE_RE.test(u));
  if (urls.length === 0 || bad.length) throw new Error(`${clone}: origin ${flags.length ? "push" : "fetch"} URL is ${bad.join(", ") || "missing"}, not ${PUBLIC_REPO}`);
}
// The clone must hold nothing of its own: no modified, staged, untracked or ignored files.
if (git(clone, "status", "--porcelain", "--ignored", "--untracked-files=all") !== "") throw new Error(`${clone} is not clean (modified, staged, untracked or ignored files); use a fresh clone`);

const branch = `source-v${values.version}`;
git(clone, "fetch", "-q", "origin");
try {
  git(clone, "rev-parse", "--verify", "-q", "origin/main");
} catch {
  throw new Error(`${PUBLIC_REPO} has no main branch to start from`);
}
const AUTHOR_EMAIL = AUTHOR.match(/<(.+)>/)[1];

// The same names build-runtime refuses to ship; a tracked one stops the publish.
const SECRET = /^(\.env(\..*)?|.*\.env|\.envrc|\.netrc|\.pgpass|\.htpasswd|\.dev\.vars(\..*)?|.*\.keychain(-db)?|.*\.mobileprovision|\.npmrc|\.git-credentials|id_(rsa|dsa|ecdsa|ed25519)(\..*)?|.*\.(pem|key|p12|pfx|p8|jks|keystore|token|gpg|asc|kubeconfig|tfvars|tfstate)|kubeconfig|terraform\.tfstate.*|secrets?(\..*)?|credentials?(\..*)?|client_secret.*|service-account.*\.json)$/i;
const BACKUP_SUFFIX = /(\.(bak|backup|orig|old|save|swp|tmp)\d*|\.\d+|\.\d{4}-\d{2}-\d{2}|~)+$/i;
// A name with a newline, a Unicode line or paragraph separator or another control or format
// character slips past line-based patterns (`.` does not match them), so it is refused outright.
const ODD_NAME = /[\p{Cc}\p{Cf}\p{Zl}\p{Zp}]/u;
const refuseOddNames = (paths) => {
  const odd = paths.filter((f) => ODD_NAME.test(f));
  if (odd.length) throw new Error(`refusing to publish: paths with control or separator characters: ${odd.map((f) => JSON.stringify(f)).join(", ")}`);
};
// The one set of guards for what may be published, run on the source tree's files and on the
// tree of the commit about to be pushed: no odd names, nothing on EXCLUDE, nothing secret-looking.
const guard = (paths) => {
  refuseOddNames(paths);
  const excluded = paths.filter((f) => EXCLUDE.some((re) => re.test(f)));
  if (excluded.length) throw new Error(`refusing to publish excluded paths: ${excluded.join(", ")}`);
  const secrets = paths.filter((f) => [path.basename(f), path.basename(f).replace(BACKUP_SUFFIX, "")].some((n) => SECRET.test(n)));
  if (secrets.length) throw new Error(`refusing to publish files that look like secrets: ${secrets.join(", ")}`);
  const inSecretsDir = paths.filter((f) => f.split("/").slice(0, -1).some((seg) => /^secrets?$/i.test(seg)));
  if (inSecretsDir.length) throw new Error(`refusing to publish files under a secrets/ folder: ${inSecretsDir.join(", ")}`);
};
const tracked = gitRaw(ROOT, "ls-files", "-z").split("\0").filter(Boolean);
refuseOddNames(tracked); // before EXCLUDE: an odd name must not be able to dodge it
const files = tracked.filter((f) => !EXCLUDE.some((re) => re.test(f)));
guard(files);
// A commit is publishable only if it passes the guards and its tree is identical, path by path and
// mode and blob id by mode and blob id, to the filtered index of the source tree. That catches an
// amended snapshot, a source that changed after the snapshot was built, and an edit made between
// the clean check and the copy (the commit holds the working-tree content; the index is what is committed).
const modeAndId = (out, sep) => new Map(out.split("\0").filter(Boolean).map((rec) => {
  const tab = rec.indexOf("\t");
  const [mode, ...rest] = rec.slice(0, tab).split(" ");
  return [rec.slice(tab + 1), `${mode} ${sep === "ls-files" ? rest[0] : rest[1]}`];
}));
const sourceEntries = modeAndId(gitRaw(ROOT, "ls-files", "-s", "-z"), "ls-files");
const verifyCommit = (ref) => {
  const inCommit = modeAndId(gitRaw(clone, "ls-tree", "-r", "-z", ref), "ls-tree");
  guard([...inCommit.keys()]);
  const want = new Set(files);
  const extra = [...inCommit.keys()].filter((f) => !want.has(f));
  const missing = files.filter((f) => !inCommit.has(f));
  if (extra.length || missing.length) throw new Error(`${ref} does not match the source tree (extra: ${extra.slice(0, 5).join(", ") || "none"}; missing: ${missing.slice(0, 5).join(", ") || "none"})`);
  const differs = files.filter((f) => inCommit.get(f) !== sourceEntries.get(f));
  if (differs.length) throw new Error(`${ref} content differs from the source tree: ${differs.slice(0, 5).join(", ")}${differs.length > 5 ? ` and ${differs.length - 5} more` : ""}; delete the branch and rebuild`);
};

// Pushes exactly this branch to the same-named branch, whatever remote.origin.push, push.default or
// push.followTags say, then opens the PR (or reports the one that exists).
const gh = (...args) => execFileSync("gh", args, { cwd: clone, encoding: "utf8" }).trim();
const openPr = () => {
  const existing = gh("pr", "list", "--repo", PUBLIC_REPO, "--head", branch, "--state", "open", "--json", "url,isCrossRepository", "--jq", "[.[] | select(.isCrossRepository == false)][0].url // empty");
  const pr = existing || gh("pr", "create", "--repo", PUBLIC_REPO, "--head", branch, "--base", "main",
    "--title", `Useful Voice ${values.version} source`, "--body", `Source snapshot of Useful Voice ${values.version}.`);
  process.stdout.write(`${pr}\n`);
};
const pushAndOpenPr = () => {
  git(clone, "push", "-q", "-u", "--no-follow-tags", "origin", `refs/heads/${branch}:refs/heads/${branch}`);
  openPr();
};
const branchExistsLocally = () => { try { git(clone, "rev-parse", "--verify", "-q", `refs/heads/${branch}`); return true; } catch { return false; } };
const remoteBranchSha = () => git(clone, "ls-remote", "--heads", "origin", `refs/heads/${branch}`).split(/\s+/)[0];
if (values["push-existing"]) {
  // Second step of preview-then-push: push the branch a previous run built, after checking it is
  // still exactly one commit on origin/main with the noreply author and committer, and that its
  // tree is exactly what this source tree would publish.
  if (!branchExistsLocally()) throw new Error(`${branch} does not exist in ${clone}; run without --push-existing first`);
  const commits = git(clone, "rev-list", `origin/main..refs/heads/${branch}`).split("\n").filter(Boolean);
  if (commits.length !== 1) throw new Error(`${branch} must be exactly one commit on origin/main, found ${commits.length}`);
  if (git(clone, "rev-parse", `refs/heads/${branch}^`) !== git(clone, "rev-parse", "origin/main")) throw new Error(`${branch} is not cut from the current origin/main`);
  const who = git(clone, "log", "-1", "--format=%ae%n%ce", `refs/heads/${branch}`).split("\n");
  if (who.length !== 2 || who.some((e) => e !== AUTHOR_EMAIL)) throw new Error(`${branch} is not authored and committed by ${AUTHOR_EMAIL}`);
  verifyCommit(`refs/heads/${branch}`);
  const remote = remoteBranchSha();
  if (remote === "") pushAndOpenPr();
  else if (remote === git(clone, "rev-parse", `refs/heads/${branch}`)) openPr(); // pushed earlier, the PR step failed: resume
  else throw new Error(`${branch} on origin is a different commit (${remote.slice(0, 7)}); delete it there to republish this version`);
  process.exit(0);
}
if (branchExistsLocally()) throw new Error(`${branch} already exists in ${clone}; run with --push-existing only if the source is unchanged since it was built, otherwise delete the branch to rebuild`);
if (remoteBranchSha() !== "") throw new Error(`${branch} already exists on origin; delete it there to republish this version`);

// Everything happens in a temporary worktree of the clone, detached at origin/main, so the
// supplied clone is untouched if any step fails. The branch is created only once the commit exists.
const work = mkdtempSync(path.join(tmpdir(), "uv-source-"));
const tree = path.join(work, "tree");
let commit = null;
const sha = git(ROOT, "rev-parse", "--short", "HEAD");
try {
  git(clone, "worktree", "add", "-q", "--detach", tree, "origin/main");
  const stage = path.join(work, "stage");
  for (const file of files) cpSync(path.join(ROOT, file), path.join(stage, file), { verbatimSymlinks: true });
  // The public tree is exactly the stage: everything else in the worktree goes.
  for (const entry of readdirSync(tree)) if (entry !== ".git") rmSync(path.join(tree, entry), { recursive: true, force: true });
  cpSync(stage, tree, { recursive: true, verbatimSymlinks: true });
  // -f: the copied .gitignore must not drop a file that is tracked here.
  git(tree, "add", "-A", "-f");
  if (git(tree, "status", "--porcelain") === "") {
    process.stdout.write(`nothing changed since the last publish (${sha})\n`);
  } else {
    execFileSync("git", ["-c", "commit.gpgsign=false", "commit", "-q", "--author", AUTHOR, "-m", `Useful Voice ${values.version} source`], {
      cwd: tree,
      env: { ...process.env, GIT_COMMITTER_NAME: "Wasim Jalali", GIT_COMMITTER_EMAIL: AUTHOR_EMAIL },
    });
    commit = git(tree, "rev-parse", "HEAD");
    verifyCommit(commit); // final check on what was actually committed, before the branch exists
    git(clone, "branch", branch, commit);
    process.stdout.write(`${JSON.stringify({ files: files.length, from: sha, branch, commit: commit.slice(0, 7) })}\n`);
  }
} finally {
  try { git(clone, "worktree", "remove", "--force", tree); } catch { /* already gone */ }
  rmSync(work, { recursive: true, force: true });
  try { git(clone, "worktree", "prune"); } catch { /* nothing to prune */ }
}

if (values.push && commit) pushAndOpenPr(); // the commit is already on the local branch, so a failed push can be retried with --push-existing
